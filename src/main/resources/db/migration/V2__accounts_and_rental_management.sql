CREATE TABLE sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  display_name VARCHAR(80) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(12) NOT NULL CHECK (role IN ('admin','provider','user')),
  provider_id BIGINT REFERENCES sys_user(id),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  auth_version BIGINT NOT NULL DEFAULT 0,
  created_ts BIGINT NOT NULL,
  CHECK ((role='user' AND provider_id IS NOT NULL) OR (role<>'user' AND provider_id IS NULL))
);
CREATE INDEX idx_user_provider ON sys_user(provider_id);

CREATE TABLE merchant (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES sys_user(id),
  provider_id BIGINT REFERENCES sys_user(id),
  name VARCHAR(80) NOT NULL,
  mch_type VARCHAR(12) NOT NULL CHECK (mch_type IN ('provider','user')),
  wechat_mch_id VARCHAR(32) NOT NULL DEFAULT '',
  wechat_sub_mch_id VARCHAR(32) NOT NULL DEFAULT '',
  alipay_app_id VARCHAR(32) NOT NULL DEFAULT ''
);

CREATE TABLE device_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
  provider_id BIGINT REFERENCES sys_user(id),
  name VARCHAR(80) NOT NULL,
  trial_minutes INTEGER NOT NULL CHECK (trial_minutes BETWEEN 0 AND 1440),
  cooldown_minutes INTEGER NOT NULL CHECK (cooldown_minutes BETWEEN 0 AND 10080),
  enabled BOOLEAN NOT NULL DEFAULT TRUE
);
